function renderInline(text: string): ReactNode[] {
  const tokenPattern =
    /(\*\*([^*]+)\*\*|\[([^\]]+)\]\((https?:\/\/[^)]+|mailto:[^)]+)\))/g;
  const nodes: ReactNode[] = [];
  let lastIndex = 0;

  for (const match of text.matchAll(tokenPattern)) {
    const index = match.index ?? 0;
    if (index > lastIndex) nodes.push(text.slice(lastIndex, index));

    if (match[2]) {
      nodes.push(<strong key={`strong-${index}`}>{match[2]}</strong>);
    } else {
      nodes.push(
        <a
          key={`link-${index}`}
          className="break-all text-primary underline underline-offset-4"
          href={match[4]}
        >
          {match[3]}
        </a>,
      );
    }
    lastIndex = index + match[0].length;
  }

  if (lastIndex < text.length) nodes.push(text.slice(lastIndex));
  return nodes;
}

function renderPolicy() {
  const lines = policy.split("\n");
  const blocks: ReactNode[] = [];
  let index = 0;

  while (index < lines.length) {
    const line = lines[index].trim();
    if (!line) {
      index += 1;
      continue;
    }

    const heading = /^(#{1,3}) (.+)$/.exec(line);
    if (heading) {
      const className =
        heading[1].length === 1
          ? "text-3xl font-semibold tracking-tight sm:text-4xl"
          : heading[1].length === 2
            ? "text-xl font-semibold"
            : "text-lg font-semibold";
      const Heading = heading[1].length === 1 ? "h1" : heading[1].length === 2 ? "h2" : "h3";
      blocks.push(
        <Heading className={className} key={`heading-${index}`}>
          {renderInline(heading[2])}
        </Heading>,
      );
      index += 1;
      continue;
    }

    if (line === "---") {
      blocks.push(<hr className="border-border" key={`rule-${index}`} />);
      index += 1;
      continue;
    }

    if (line.startsWith("- ")) {
      const items: ReactNode[] = [];
      while (index < lines.length && lines[index].trim().startsWith("- ")) {
        const item = lines[index].trim().slice(2);
        items.push(<li key={`item-${index}`}>{renderInline(item)}</li>);
        index += 1;
      }
      blocks.push(
        <ul
          className="list-disc space-y-2 pl-6 marker:text-muted-foreground"
          key={`list-${index}`}
        >
          {items}
        </ul>,
      );
      continue;
    }

    const paragraph = [line];
    index += 1;
    while (
      index < lines.length &&
      lines[index].trim() &&
      !/^(#{1,3} |- |---$)/.test(lines[index].trim())
    ) {
      paragraph.push(lines[index].trim());
      index += 1;
    }
    blocks.push(
      <p key={`paragraph-${index}`}>{renderInline(paragraph.join(" "))}</p>,
    );
  }

  return blocks;
}

